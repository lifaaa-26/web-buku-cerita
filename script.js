// ELEMEN WEBSITE
const loginPage = document.getElementById("loginPage");
const mainWebsite = document.getElementById("mainWebsite");
const loginForm = document.getElementById("loginForm");
const reader = document.getElementById("reader");

let selectedCategory = "Semua";

// LOGIN
loginForm.addEventListener("submit", function(event) {
    event.preventDefault();

    const username = document.getElementById("username").value.trim();
    const password = document.getElementById("password").value;

    if (username.length < 2 || password.length < 4) {
        document.getElementById("loginMessage").textContent =
            "Nama minimal 2 karakter dan kata sandi minimal 4 karakter.";
        return;
    }

    localStorage.setItem("ceritakitaUser", username);
    showWebsite(username);
});

function showWebsite(username) {
    loginPage.classList.add("hidden");
    mainWebsite.classList.remove("hidden");

    document.getElementById("welcomeUser").textContent =
        "Halo, " + username;

    renderFeatured();
    renderStories();
}

// NAVIGASI
function showPage(page) {
    document.querySelectorAll(".page").forEach(section => {
        section.classList.add("hidden");
    });

    document.getElementById(page).classList.remove("hidden");
    document.getElementById("navigation").classList.remove("open");

    window.scrollTo({top: 0, behavior: "smooth"});
}

document.querySelectorAll("[data-page]").forEach(button => {
    button.addEventListener("click", () => {
        showPage(button.dataset.page);
    });
});

document.querySelectorAll("[data-go]").forEach(button => {
    button.addEventListener("click", () => {
        showPage(button.dataset.go);
    });
});

// KARTU CERITA
function createCard(story, index) {
    return `
    <div class="story-card">
        <div class="story-art" style="--art:${story.color}">
            ${story.emoji}
        </div>
        <div class="story-info">
            <span class="category-label">${story.category}</span>
            <h3>${story.title}</h3>
            <p>${story.description}</p>
            <button class="read-button" data-read="${index}">
                Baca Selengkapnya →
            </button>
        </div>
    </div>`;
}

function renderFeatured() {
    document.getElementById("featuredStories").innerHTML =
        stories.slice(0, 3).map((story, index) =>
            createCard(story, index)
        ).join("");
}

// KOLEKSI CERITA
function renderStories() {
    const keyword = document.getElementById("search").value.toLowerCase();

    const filtered = stories.map((story, index) => ({
        ...story,
        index
    })).filter(story => {
        const categoryMatch =
            selectedCategory === "Semua" ||
            story.category === selectedCategory;

        const searchMatch =
            (story.title + " " + story.description)
            .toLowerCase().includes(keyword);

        return categoryMatch && searchMatch;
    });

    document.getElementById("allStories").innerHTML =
        filtered.map(story =>
            createCard(story, story.index)
        ).join("");

    document.getElementById("storyCount").textContent =
        `Menampilkan ${filtered.length} dari ${stories.length} cerita`;

    document.getElementById("emptyMessage").classList.toggle(
        "hidden", filtered.length !== 0
    );
}

document.getElementById("search").addEventListener("input", renderStories);

document.querySelectorAll(".filter").forEach(button => {
    button.addEventListener("click", () => {
        selectedCategory = button.dataset.category;

        document.querySelectorAll(".filter").forEach(item => {
            item.classList.remove("active");
        });

        button.classList.add("active");
        renderStories();
    });
});

// BUKA CERITA
document.addEventListener("click", event => {
    const button = event.target.closest("[data-read]");

    if (button) {
        openStory(Number(button.dataset.read));
    }
});

function openStory(index) {
    const story = stories[index];

    document.getElementById("readerCategory").textContent =
        story.category;

    document.getElementById("readerTitle").textContent =
        story.title;

    document.getElementById("readerDescription").textContent =
        story.description;

    document.getElementById("readerContent").innerHTML =
        story.paragraphs.map(paragraph =>
            `<p>${paragraph}</p>`
        ).join("");

    document.getElementById("readerMoral").textContent =
        story.moral;

    reader.classList.remove("hidden");
    document.body.style.overflow = "hidden";
}

function closeStory() {
    reader.classList.add("hidden");
    document.body.style.overflow = "";
}

document.getElementById("closeReader").addEventListener("click", closeStory);
document.getElementById("backCollection").addEventListener("click", closeStory);

reader.addEventListener("click", event => {
    if (event.target === reader) closeStory();
});

document.addEventListener("keydown", event => {
    if (event.key === "Escape") closeStory();
});

// DARK MODE
document.getElementById("darkMode").addEventListener("click", () => {
    document.body.classList.toggle("dark");

    const isDark = document.body.classList.contains("dark");

    localStorage.setItem("ceritakitaTheme", isDark ? "dark" : "light");

    document.getElementById("darkMode").textContent =
        isDark ? "☀️" : "🌙";
});

if (localStorage.getItem("ceritakitaTheme") === "dark") {
    document.body.classList.add("dark");
    document.getElementById("darkMode").textContent = "☀️";
}

